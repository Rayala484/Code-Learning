  const textOriginals = new WeakMap();
  const attrOriginals = new WeakMap();
  const htmlOriginals = new WeakMap();
  let titleOriginal = null;

  const t = (s) => (lang === "te" ? TE[norm(String(s))] || s : s);

  const skip = (el) => !el || el.closest("script, style, [data-i18n-html], [translate='no']");

  function apply(root) {
    root = root || document.body;
    if (!root) return;

    // 1. Mixed-markup headings: swap the whole inner HTML.
    const blocks = [...root.querySelectorAll("[data-i18n-html]")];
    if (root.matches && root.matches("[data-i18n-html]")) blocks.push(root);
    blocks.forEach((el) => {
      if (!htmlOriginals.has(el)) htmlOriginals.set(el, el.innerHTML);
      const key = el.getAttribute("data-i18n-html");
      el.innerHTML = lang === "te" && TE_HTML[key] ? TE_HTML[key] : htmlOriginals.get(el);
    });

    // 2. Plain text nodes.
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.nodeValue.trim() && !skip(n.parentElement) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT),
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const cur = node.nodeValue;
      const known = textOriginals.get(node);
      // New node, or the page changed this text since we last saw it: treat it as the English original.
      if (known === undefined || (cur !== known && cur.trim() !== (TE[norm(known)] || ""))) textOriginals.set(node, cur);
      const orig = textOriginals.get(node);
      if (lang === "en") { if (node.nodeValue !== orig) node.nodeValue = orig; return; }
      const tr = TE[norm(orig)];
      if (!tr) return;
      const lead = orig.match(/^\s*/)[0];
      const trail = orig.match(/\s*$/)[0];
      node.nodeValue = lead + tr + trail;
    });

    // 3. Attributes (placeholders, labels, alt text).
    const sel = ATTRS.map((a) => `[${a}]`).join(",");
    const els = [...root.querySelectorAll(sel)];
    if (root.matches && root.matches(sel)) els.push(root);
    els.forEach((el) => {
      if (el.closest("[translate='no']")) return;
      let store = attrOriginals.get(el);
      if (!store) { store = {}; attrOriginals.set(el, store); }
      ATTRS.forEach((a) => {
        if (!el.hasAttribute(a)) return;
        const cur = el.getAttribute(a);
        if (!(a in store) || (cur !== store[a] && cur !== TE[norm(store[a])])) store[a] = cur;
        const v = lang === "te" ? TE[norm(store[a])] || store[a] : store[a];
        if (el.getAttribute(a) !== v) el.setAttribute(a, v);
      });
    });
  }

  function applyDocument() {
    if (titleOriginal === null) titleOriginal = document.title;
    document.title = lang === "te" ? TE[norm(titleOriginal)] || titleOriginal : titleOriginal;
    document.documentElement.lang = lang;
    apply(document.body);
  }

  function setLang(next) {
    lang = next === "te" ? "te" : "en";
    try { localStorage.setItem(STORE_KEY, lang); } catch (e) { /* storage blocked */ }
    applyDocument();
    document.dispatchEvent(new CustomEvent("gx:langchange", { detail: { lang } }));
  }

  window.GX_I18N = { t, apply, setLang, get lang() { return lang; } };

